import hashlib

from config import PHONE


def _h(seed, n):
    return int(hashlib.md5(seed.encode()).hexdigest(), 16) % n


def _hs(seed):
    return int(hashlib.md5(seed.encode()).hexdigest(), 16)


def _batchim(word):
    ch = word[-1]
    if "가" <= ch <= "힣":
        return (ord(ch) - 0xAC00) % 28 != 0
    return False


def J(w, a, b):
    return w + (a if _batchim(w) else b)


# ---------------------------------------------------------------- 동 분류
def classify(dong):
    """(유형, 어근) — 유형: dong|eup|myeon"""
    if dong.endswith("읍"):
        return "eup", dong[:-1]
    if dong.endswith("면"):
        return "myeon", dong[:-1]
    base = dong[:-1] if dong.endswith(("동", "가")) else dong
    return "dong", base


